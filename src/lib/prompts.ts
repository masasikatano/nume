/**
 * ユーザーメッセージを組み立てる。計算済みナンバーはサーバー側が正とする。
 */
export function buildUserPrompt(birthdate: string, lifePath: number): string {
  return [
    `生年月日: ${birthdate}`,
    `ライフパスナンバー: ${lifePath}`,
    '',
    `この生年月日の方のライフパスナンバーは ${lifePath} です（計算済みのため確実です）。`,
    'この方へのパーソナライズされた解説を、指定された構成と分量で書いてください。',
  ].join('\n');
}

